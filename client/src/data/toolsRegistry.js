// Derived constants
export const CATEGORIES = [...new Set(TOOLS.map((t) => t.category))];

export const POPULAR_TOOLS = TOOLS.filter((t) => t.popular);

export const TOOLS_BY_CATEGORY = CATEGORIES.reduce((acc, cat) => {
  acc[cat] = TOOLS.filter((t) => t.category === cat);
  return acc;
}, {});

export const getToolById = (id) => TOOLS.find((t) => t.id === id);
export const getToolsByCategory = (category) => TOOLS.filter((t) => t.category === category);
export const searchTools = (query) => {
  const q = query.toLowerCase();
  return TOOLS.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q)
  );
};

